import { RunState, StudioSettings } from './types';
import { sanitizeContent } from './sanitizer';

export interface ExportRunData {
  runState: RunState;
  settings: StudioSettings;
}

export function toAttemptsJsonl(data: ExportRunData): string {
  const { runState, settings } = data;
  const entries = [...runState.entries].sort((a, b) => a.index - b.index);

  const keptCount = entries.filter(e => e.status === 'kept').length;
  const rejectedCount = entries.filter(e => e.status === 'rejected').length;
  const errorCount = entries.filter(e => e.status === 'error').length;

  const modelCounts: Record<string, number> = {};
  for (const e of entries) {
    const m = e.modelUsed || settings.model;
    modelCounts[m] = (modelCounts[m] || 0) + 1;
  }

  const headerObj = {
    type: 'header',
    schema: 'repeated-answers/v2-emg',
    runId: runState.runId,
    question: settings.question,
    engine: settings.engine,
    selectedModel: settings.model,
    shape: settings.shape,
    abstraction: settings.abstraction,
    highThinking: settings.highThinking,
    embeddingThreshold: settings.embeddingThreshold,
    localThreshold: settings.localThreshold,
    tagThreshold: settings.tagThreshold,
    emgGatesEnabled: settings.emgGatesEnabled ?? true,
    emgSanitizeSecrets: settings.emgSanitizeSecrets ?? true,
    emgMinEntropy: settings.emgMinEntropy ?? 3.6,
    target: settings.target,
    startedAt: new Date(runState.startTime || Date.now()).toISOString(),
    exportedAt: new Date().toISOString(),
    attempts: entries.length,
    kept: keptCount,
    rejected: rejectedCount,
    errors: errorCount,
    modelCounts,
  };

  const lines = [JSON.stringify(headerObj)];

  for (const e of entries) {
    const attemptObj = {
      type: 'attempt',
      runId: runState.runId,
      index: e.index,
      status: e.status,
      text: e.text,
      coreIdea: e.coreIdea || null,
      observableConsequence: e.observableConsequence ?? null,
      counterevidence: e.counterevidence ?? null,
      reason: e.reason || null,
      embeddingSimilarity: e.similarityScore ?? null,
      tagSimilarity: e.tagSimilarity ?? null,
      closestMatchIndex: e.closestMatchIndex ?? null,
      shannonEntropy: e.shannonEntropy ?? null,
      sanitizedSecrets: e.sanitizedSecrets && e.sanitizedSecrets.length > 0 ? e.sanitizedSecrets : null,
      emgAuditPassed: e.emgAuditPassed ?? null,
      persona: e.persona || null,
      timestamp: new Date(e.timestamp || Date.now()).toISOString(),
      selectedModel: settings.model,
      modelUsed: e.modelUsed || settings.model,
      fallbackUsed: e.fallbackUsed ?? false,
    };
    lines.push(JSON.stringify(attemptObj));
  }

  const result = lines.join('\n') + '\n';
  return settings.emgSanitizeSecrets ? sanitizeContent(result).sanitized : result;
}

export function toKeptMarkdown(data: ExportRunData): string {
  const { runState, settings } = data;
  const keptEntries = runState.entries
    .filter(e => e.status === 'kept')
    .sort((a, b) => a.index - b.index);

  let md = `# Repeated Answers Studio: Kept Insights\n\n`;
  md += `- **Question**: ${settings.question}\n`;
  md += `- **Run ID**: ${runState.runId}\n`;
  md += `- **Selected Model**: ${settings.model}\n`;
  md += `- **Persona Mode**: ${settings.personaMode || 'rotate'}\n`;
  md += `- **Generated At**: ${new Date(runState.startTime || Date.now()).toISOString()}\n\n`;
  md += `These answers were generated by a language model and have not been checked for accuracy.\n\n`;
  md += `---\n\n`;

  keptEntries.forEach((e, idx) => {
    const ideaTitle = e.coreIdea ? ` — ${e.coreIdea}` : '';
    md += `### ${idx + 1}. Insight #${e.index}${ideaTitle}\n\n`;
    md += `${e.text}\n\n`;
    if (e.observableConsequence) {
      md += `- **Observable prediction**: ${e.observableConsequence}\n\n`;
    }
    if (e.counterevidence) {
      md += `- **Counterevidence**: ${e.counterevidence}\n\n`;
    }
    if (e.persona) {
      md += `*Lens: \`${e.persona}\`* · `;
    }
    if (e.shannonEntropy) {
      md += `*EMG Entropy: \`${e.shannonEntropy.toFixed(2)} bits/char\`* · `;
    }
    if (e.modelUsed) {
      md += `*Model: \`${e.modelUsed}\`*\n\n`;
    } else {
      md += `\n\n`;
    }
    md += `---\n\n`;
  });

  return settings.emgSanitizeSecrets ? sanitizeContent(md).sanitized : md;
}
